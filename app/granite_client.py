"""
IBM Granite AI client — wraps ibm-watsonx-ai SDK for all LLM calls.
Compatible with ibm-watsonx-ai >= 1.5.14 (Python 3.15 safe).
"""
from __future__ import annotations

from app.config import settings


def granite_generate(prompt: str, model_id: str | None = None) -> str:
    """
    Send a prompt to IBM Granite and return the generated text.
    Falls back to a structured mock when credentials are not configured,
    so the app remains fully usable during development / demo.
    """
    if not settings.IBM_WATSONX_API_KEY or settings.IBM_WATSONX_API_KEY == "your_ibm_cloud_api_key_here":
        return _mock_response(prompt)

    try:
        from ibm_watsonx_ai import Credentials
        from ibm_watsonx_ai.foundation_models import ModelInference

        mid = model_id or settings.GRANITE_MODEL_ID
        model = ModelInference(
            model_id=mid,
            credentials=Credentials(
                url=settings.IBM_WATSONX_URL,
                api_key=settings.IBM_WATSONX_API_KEY,
            ),
            project_id=settings.IBM_WATSONX_PROJECT_ID,
            params={
                "max_new_tokens": settings.GRANITE_MAX_TOKENS,
                "temperature": settings.GRANITE_TEMPERATURE,
                "top_p": settings.GRANITE_TOP_P,
            },
        )
        return model.generate_text(prompt=prompt)
    except Exception as exc:
        return f"[IBM Granite error: {exc}]\n\n{_mock_response(prompt)}"


